#!/usr/bin/env python3
# Audit k_47 (copied from audit/k41_k43/elim.py; added: the option RULE+dropA,B that leaves out the data lines A, B of the certificate).
# Audit k_41, k_43, step 2: own elimination over A = Z[x]/(Phi_p) on the rows of out/rows_P.json (made by rows.py).
# Nothing from relations/ is imported.  The algorithm is the one of audit/k37/elim_own.py (read, and rewritten for general p with a
# choice of the pivot rule).  Differences from relations/span.py: no row is dropped; no prime is removed beforehand; another pivot
# order; the elimination continues as long as an entry +-x^j exists (span.py stops at 120 columns).
# Mathematics: X = A^T / L (generators e_q, relations = rows).  If the row r has the entry u = +-x^j at q (a unit of A), then
# e_q = -u^(-1) sum_{q' != q} r_q' e_q' in X, so X is isomorphic to A^(T - q) / L', L' generated by the rows r_k - (r_k,q u^(-1)) r
# (k != i) without the column q.  The inverse u^(-1) = +-x^(p-j) is checked by multiplication at every pivot.
#   python3 elim.py p RULE SECONDS [resume]      RULE = markowitz | sparsecol | random:SEED   ->  out/elim_P_RULE.pkl
#     markowitz: smallest (r-1)(c-1) among the unit entries of the 60 sparsest columns that have one (as audit/k37)
#     sparsecol: the sparsest column that has a unit entry; in it the row with the fewest entries
#     random:SEED: a random unit entry among those of the 8 sparsest columns that have one
#   CONTROL (not part of the verification): RULE+ctlQ multiplies all entries of the column of the prime Q by 1 - x before the elimination.
#     If the true rows generate A^T, the modified rows generate a submodule of index Nm(1 - x) = p, so core.py must end with a gcd that is
#     a multiple of p (and equal to p when enough sets are used), never 1.
import sys, json, pickle, time, random
from flint import fmpz_poly
from fieldp import need
p=int(sys.argv[1]); rule=sys.argv[2]; budget=float(sys.argv[3]); tag="%d_%s"%(p,rule.replace(":","")); t0=time.time()
dropped=[int(v) for v in rule.split("+drop")[1].split(",")] if "+drop" in rule else []; rule=rule.split("+drop")[0]   # k_47 audit: lines left out (0-based data lines)
ctl=int(rule.split("+ctl")[1]) if "+ctl" in rule else None; rule=rule.split("+ctl")[0]       # control: see the usage line
Phi=fmpz_poly([1]*p); ZERO=fmpz_poly([]); ONE=fmpz_poly([1])
def red(a): return a%Phi
def mono(j,sg): return red(fmpz_poly([0]*(j%p)+[sg]))
def unit(a):                                          # (sign, j) with a = sign x^j (0 <= j <= p-1), or None
    co=[int(v) for v in a.coeffs()]; nz=[j for j,v in enumerate(co) if v]
    if len(nz)==1 and abs(co[nz[0]])==1: return co[nz[0]],nz[0]
    if len(co)==p-1 and len(set(co))==1 and abs(co[0])==1: return -co[0],p-1      # x^(p-1) = -(1 + ... + x^(p-2))
    return None
if len(sys.argv)>4:
    st=pickle.load(open("out/elim_%s.pkl"%tag,"rb"))
    rows=[{q:fmpz_poly(v) for q,v in r.items()} for r in st["rows"]]; alive=set(st["alive"]); T=st["T"]; npiv=st["npiv"]; cols=set(st["cols"]); rng=random.Random(st["rngseed"])
else:
    raw=json.load(open("out/rows_%d.json"%p)); rows=[]
    for r in raw:
        d={}
        for q,J in r:
            e=[0]*p
            for j in J: e[j]+=1
            need(set(e)<={0,1},"J has a repeated index")
            v=red(fmpz_poly(e))                       # sum_{j in J} x^j in A
            if q==ctl: v=red(v*fmpz_poly([1,-1]))        # control only: the column of the prime ctl is multiplied by 1 - x
            if v!=ZERO: d[q]=v
        rows.append(d)
    for i in dropped: rows[i]={}                    # a dropped line contributes nothing; primes that occur only in dropped lines leave T
    alive=set(i for i,r in enumerate(rows) if r); T=sorted(set(q for r in rows for q in r)); cols=set(T); npiv=0
    rng=random.Random(int(rule.split(":")[1]) if rule.startswith("random") else 0)
    print("field k_%d, rule %s; rows: %d (nonzero %d); T: %d primes, smallest %s, largest %d"%(p,rule,len(rows),len(alive),len(T),T[:6],T[-1]),flush=True)
col={q:set() for q in cols}
for i in alive:
    for q in rows[i]: col[q].add(i)
need(all(set(rows[i])<=cols for i in alive),"support")
stuck=False
while cols and time.time()-t0<budget:
    cands=[]; found=0; lim={"markowitz":60,"sparsecol":1}.get(rule.split(":")[0],8)
    for q in sorted(cols,key=lambda q:(len(col[q]),q)):
        if found>=lim: break
        hit=False
        for i in sorted(col[q]):
            u=unit(rows[i][q])
            if u is not None:
                hit=True
                cost=((len(rows[i])-1)*(len(col[q])-1),q,i) if rule=="markowitz" else (len(rows[i]),q,i)
                cands.append((cost,u))
        if hit: found+=1
    if not cands: stuck=True; break
    (cost,q,i),(sg,j)=rng.choice(cands) if rule.startswith("random") else min(cands)
    r=rows[i]; inv=mono(p-j,sg)
    need(red(r[q]*inv)==ONE,"pivot inverse")
    others=[(q2,x) for q2,x in r.items() if q2!=q]
    for k in list(col[q]):
        if k==i: continue
        rk=rows[k]; fct=red(rk[q]*inv)
        for q2,x in others:
            y=rk.get(q2,ZERO)-red(fct*x)
            if y!=ZERO: rk[q2]=y; col[q2].add(k)
            elif q2 in rk: del rk[q2]; col[q2].discard(k)
        del rk[q]
        if not rk: alive.discard(k)
    for q2,x in others: col[q2].discard(i)
    alive.discard(i); del col[q]; cols.discard(q); npiv+=1
    if npiv%500==0 or len(cols)<250 and npiv%20==0:
        nz=sum(len(rows[k]) for k in alive); mx=max((max((abs(int(c)) for c in e.coeffs()),default=0) for k in alive for e in rows[k].values()),default=0)
        print("pivots %d; columns %d; rows %d; nonzero entries %d; largest coefficient %d digits; %.0f s"%(npiv,len(cols),len(alive),nz,len(str(mx)),time.time()-t0),flush=True)
need(all(set(rows[i])<=cols for i in alive),"support at the end")
empty=[q for q in cols if not col[q]]
print("STATE k_%d %s: pivots %d; columns left %d (empty columns: %d); rows left %d; %s; %.0f s"%(p,rule,npiv,len(cols),len(empty),len(alive),"no entry +-x^j left" if stuck else ("finished" if not cols else "time budget reached"),time.time()-t0),flush=True)
pickle.dump({"rows":[{q:[int(c) for c in v.coeffs()] for q,v in r.items()} if i in alive else {} for i,r in enumerate(rows)],"alive":sorted(alive),"T":T,"npiv":npiv,"cols":sorted(cols),"stuck":stuck,"rngseed":rng.random()},open("out/elim_%s.pkl"%tag,"wb"))
