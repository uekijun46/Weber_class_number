#!/usr/bin/env python3
# Audit k_37: checks of the field model of field37.py against PARI, and the Galois action in the power basis of eta_0.
# Output: out/model.txt (text), out/galois.json (eta_i as polynomials in eta_0: integer numerators and a common denominator).
import sys, json
import cypari2
from field37 import Field, need, read_cert
pari=cypari2.Pari(); pari.allocatemem(2*10**9)
p=37; F=Field(p)
E0=F.mul_matrix(F.elem(0,[(0,1)]))                   # multiplication by eta_0
f=pari.matrix(p,p,[x for r in E0 for x in r]).charpoly()
fs=pari('polsubcyclo(1369,37)')
print("g =",F.g)
print("charpoly of multiplication by eta_0 == polsubcyclo(1369,37):",f==fs)
need(pari.polisirreducible(f),"charpoly is reducible")
print("irreducible: True  (so 1, eta_0, ..., eta_35 is a Q-basis of K and the table is the regular representation)")
D=pari.poldisc(f); nd=pari.nfdisc(f)
print("nfdisc =",pari.factor(nd))
need(nd==pari(37)**72,"field discriminant")
ind2=D//nd; need(D==nd*ind2,"disc"); ind=pari.sqrtint(ind2); need(ind*ind==ind2,"index is not a square root")
print("index [O_K : Z[eta_0]] has %d digits; small factors (trial division up to 10^7): %s"%(len(str(ind)),pari.factor(ind,10**7)))
# lattice generated by 1, eta_0..eta_35: discriminant = det(Tr(b_i b_j))
def trace(v): 
    M_=F.mul_matrix(v); return sum(M_[i][i] for i in range(p))
basis=[[1]+[0]*(p-1)]+[[0]*(1+k)+[1]+[0]*(p-2-k) for k in range(p-1)]
def mul(u,v):
    Mv=F.mul_matrix(v); return [sum(u[k]*Mv[k][t] for k in range(p)) for t in range(p)]
G=[[trace(mul(basis[i],basis[j])) for j in range(p)] for i in range(p)]
dG=pari.matrix(p,p,[x for r in G for x in r]).matdet()
print("discriminant of Z[1, eta_0, ..., eta_35] =",pari.factor(dG)," => index in O_K =",pari.sqrtint(dG//nd))
# eta_i as polynomials in eta_0
pw=[basis[0]]; e0=basis[1]
for k in range(1,p): pw.append(mul(pw[-1],e0))
P=pari.matrix(p,p,[x for r in pw for x in r])       # row k: coordinates of eta_0^k
need(P.matdet()!=0,"powers of eta_0 are dependent")
Pinv=P**(-1)                                          # row t of Pinv: basis element t as a combination of powers of eta_0
den=pari.denominator(Pinv); Pi=Pinv*den
print("common denominator of the basis in powers of eta_0: %d digits; equal to the index: %s; factor(den, 10^7) = %s"%(len(str(den)),den==ind,pari.factor(den,10**7)))
x=pari('x')
polys=[]
for i in range(p):
    v=F.elem(0,[(i,1)])
    co=[sum(v[t]*Pi[t,k] for t in range(p)) for k in range(p)]
    polys.append([int(c) for c in co])
# check: g_i(eta_0) = eta_i in K (exactly), by evaluating in the regular representation
for i in (1,2,36):
    acc=[0]*p
    for k in range(p):
        for t in range(p): acc[t]+=polys[i][k]*pw[k][t]
    need(acc==[int(den)*c for c in F.elem(0,[(i,1)])],"g_%d(eta_0) != eta_%d"%(i,i))
# check: g_1(g_i(x)) = g_(i+1)(x) mod f  (Galois action tau: eta_i -> eta_(i+1) is the field automorphism eta_0 -> eta_1)
fm=pari.Mod(1,f)
g=[pari.Pol(list(reversed(c)))/den for c in polys]
ok=all(pari.lift(pari.subst(g[i],x,pari.Mod(g[1],f)))==g[(i+1)%p] for i in range(p))
print("g_i(g_1(x)) = g_(i+1)(x) mod f for all i mod 37:",ok); need(ok,"galois")
ok2=all(pari.lift(pari.subst(f,x,pari.Mod(g[i],f)))==0 for i in range(p)); need(ok2,"f(g_i)!=0")
print("f(g_i(x)) = 0 mod f for all i:",ok2)
json.dump({"den":str(den),"polys":[[str(c) for c in pl] for pl in polys],"f":[str(c) for c in pari.Vecrev(f)]},open("out/galois.json","w"))
# threshold 149 and the prime above 37
best=None
for l in range(2,2000):
    if l==p or not pari.isprime(l): continue
    o=int(pari.znorder(pari.Mod(l,p)))
    if best is None or l**o<best[0]: best=(l**o,l,o)
print("min over primes l != 37, l < 2000 of l^(order of l mod 37) = %d (l=%d, order %d)"%best)
print("orders mod 37 of 2,3,5,7,11,13:",[int(pari.znorder(pari.Mod(l,p))) for l in (2,3,5,7,11,13)],"; 73 mod 37 order",int(pari.znorder(pari.Mod(73,p))))
# pi = prod_{h in H} (1 - zeta^h): norm to Q is Phi_M(1) = p.  Its coordinates in the period basis and the determinant of its regular representation.
M=F.M
cnt=[0]*M; cnt[0]=1
for h in F.H:
    new=[0]*M
    for e in range(M):
        if cnt[e]: new[e]+=cnt[e]; new[(e+h)%M]-=cnt[e]
    cnt=new
const=cnt[0]; mp=set(cnt[p*k] for k in range(1,p)); need(len(mp)==1,"pi: multiples of p"); const-=mp.pop()
m=[]
for k in range(p):
    s=set(cnt[e] for e in F.E[k]); need(len(s)==1,"pi: coset"); m.append(s.pop())
v=F.reduce(const,m); dpi=pari.matrix(p,p,[x_ for r in F.mul_matrix(v) for x_ in r]).matdet()
print("pi = prod_{h in H}(1 - zeta^h) lies in Z[1, eta_i]; N(pi) =",dpi)
need(abs(int(dpi))==37,"norm of pi")
