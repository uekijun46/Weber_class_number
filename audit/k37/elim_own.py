#!/usr/bin/env python3
# Audit k_37, step 2: own elimination over A = Z[x]/(Phi_37) on the rows of out/rows.json (made by rows37.py).
# Nothing from relations/ is imported.  Differences from relations/span.py: no row is dropped, no prime is removed beforehand,
# the pivot order is different (smallest Markowitz cost (r-1)(c-1) among all entries +-x^j in the 60 sparsest columns that have one),
# and the elimination continues as long as an entry +-x^j exists (span.py stops at 120 columns).
# Mathematics: the module is X = A^T / L (generators e_q, relations = rows).  If the row r has the entry u = +-x^j at q, then
# e_q = -u^(-1) sum_{q' != q} r_q' e_q' in X, so X is isomorphic to A^(T - q) / L', L' generated by r_k - (r_k,q u^(-1)) r without the column q.
# State is saved in out/elim_state.pkl (entries as lists of integers) so that the run can be split.
#   python3 elim_own.py SECONDS [resume]
import sys, json, pickle, time
from flint import fmpz_poly
from field37 import need
p=37; Phi=fmpz_poly([1]*p); ZERO=fmpz_poly([]); ONE=fmpz_poly([1])
def red(a): return a%Phi
def mono(j,sg): return red(fmpz_poly([0]*(j%p)+[sg]))
def unit(a):                                          # (sign, j) with a = sign x^j, or None
    co=[int(v) for v in a.coeffs()]; nz=[j for j,v in enumerate(co) if v]
    if len(nz)==1 and abs(co[nz[0]])==1: return co[nz[0]],nz[0]
    if len(co)==p-1 and len(set(co))==1 and abs(co[0])==1: return -co[0],p-1
    return None
budget=float(sys.argv[1]); t0=time.time()
if len(sys.argv)>2:
    st=pickle.load(open("out/elim_state.pkl","rb"))
    rows=[{q:fmpz_poly(v) for q,v in r.items()} for r in st["rows"]]; alive=set(st["alive"]); T=st["T"]; npiv=st["npiv"]; cols=set(st["cols"]); log=st["log"]
else:
    raw=json.load(open("out/rows.json")); rows=[]
    for r in raw:
        d={}
        for q,J in r:
            e=[0]*p
            for j in J: e[j]=1
            v=red(fmpz_poly(e))
            if v!=ZERO: d[q]=v
        rows.append(d)
    alive=set(i for i,r in enumerate(rows) if r); T=sorted(set(q for r in rows for q in r)); cols=set(T); npiv=0; log=[]
    print("rows: %d (nonzero %d); T: %d primes, smallest %s, largest %d"%(len(rows),len(alive),len(T),T[:6],T[-1]),flush=True)
col={q:set() for q in cols}
for i in alive:
    for q in rows[i]: col[q].add(i)
need(all(set(rows[i])<=cols for i in alive),"support")
stuck=False
while cols and time.time()-t0<budget:
    best=None; found=0
    for q in sorted(cols,key=lambda q:(len(col[q]),q)):
        if found>=60: break
        hit=False
        for i in col[q]:
            u=unit(rows[i][q])
            if u is not None:
                hit=True; cost=((len(rows[i])-1)*(len(col[q])-1),q,i)
                if best is None or cost<best[0]: best=(cost,u)
        if hit: found+=1
        if best is not None and best[0][0]==0: break
    if best is None: stuck=True; break
    (cost,q,i),(sg,j)=best; r=rows[i]; inv=mono(p-j,sg)
    need(red(r[q]*inv)==ONE,"pivot inverse")
    others=[(q2,x) for q2,x in r.items() if q2!=q]
    for k in list(col[q]):
        if k==i: continue
        rk=rows[k]; fct=red(rk[q]*inv)
        for q2,x in others:
            y=rk.get(q2,ZERO)-red(fct*x)
            if y!=ZERO: rk[q2]=y; col[q2].add(k)
            elif q2 in rk: del rk[q2]; col[q2].discard(k)
        del rk[q]
        if not rk: alive.discard(k)
    for q2,x in others: col[q2].discard(i)
    alive.discard(i); del col[q]; cols.discard(q); npiv+=1; log.append((q,i,sg,j))
    if npiv%200==0 or len(cols)<150 and npiv%10==0:
        nz=sum(len(rows[k]) for k in alive); mx=max((max((abs(int(c)) for c in e.coeffs()),default=0) for k in alive for e in rows[k].values()),default=0)
        print("pivots %d; columns %d; rows %d; nonzero entries %d; largest coefficient %d digits; %.0f s"%(npiv,len(cols),len(alive),nz,len(str(mx)),time.time()-t0),flush=True)
need(all(set(rows[i])<=cols for i in alive),"support at the end")
empty=[q for q in cols if not col[q]]
print("STATE: pivots %d; columns left %d (empty columns: %d); rows left %d; %s; %.0f s"%(npiv,len(cols),len(empty),len(alive),"no entry +-x^j left" if stuck else ("finished" if not cols else "time budget reached"),time.time()-t0),flush=True)
pickle.dump({"rows":[{q:[int(c) for c in v.coeffs()] for q,v in r.items()} if i in alive else {} for i,r in enumerate(rows)],"alive":sorted(alive),"T":T,"npiv":npiv,"cols":sorted(cols),"log":log,"stuck":stuck},open("out/elim_state.pkl","wb"))
