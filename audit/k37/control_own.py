#!/usr/bin/env python3
# Audit k_37, control experiments with the audit's own rows: cyclic fields K of prime degree d and prime conductor l (d | l-1) with
# KNOWN class number h (PARI, certified; control_fields.py).  Rows are built by this file (not by span.py / span_test.py):
#   eta_i = sum_{e in g^i H} zeta_l^e (normal integral basis, sum eta_i = -1); alpha = sum b_i eta_i with |b_i| <= B;
#   norm = determinant of the regular representation (PARI); factorization by trial division; ring homomorphisms O_K -> F_q by linear
#   algebra modulo q, verified against the multiplication table.  Only relations with all valuations 0/1 are kept (as in span_test.py).
# The same rows are then given to (1) the audit's ownspan.own_span and (2) the author's span.prove (imported here on purpose, as the
# object under test).  Expected: h = 1 -> gcd 1;  h > 1 -> gcd > 1 (a multiple of the order of the subgroup generated by T).
# With "tamper": one entry of one row is multiplied by x (the pattern J is shifted by one), and both are run again.
#   python3 control_own.py l d B Y h [tamper]
import sys, os, io, itertools, contextlib, random
sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","..","relations"))
import cypari2
from nmdet import need, pari
from ownspan import own_span
l,d,B,Y,h=[int(v) for v in sys.argv[1:6]]; tamper=len(sys.argv)>6
need(pari.isprime(l) and pari.isprime(d) and (l-1)%d==0,"field")
g=int(pari.lift(pari.znprimroot(l))); H=[pow(g,d*t,l) for t in range((l-1)//d)]; E=[sorted(pow(g,i,l)*x%l for x in H) for i in range(d)]
need(sorted(e for S in E for e in S)==list(range(1,l)),"cosets")
prod=[[None]*d for _ in range(d)]                     # eta_i eta_j = sum_k prod[i][j][k] eta_k
for i in range(d):
    for j in range(d):
        cnt=[0]*l
        for a in E[i]:
            for b in E[j]: cnt[(a+b)%l]+=1
        m=[]
        for k in range(d):
            s=set(cnt[e] for e in E[k]); need(len(s)==1,"coset multiplicity"); m.append(s.pop()-cnt[0])
        prod[i][j]=m
def mulmat(v): return [[sum(v[i]*prod[i][b][k] for i in range(d)) for k in range(d)] for b in range(d)]      # row b: v * eta_b
def mul(u,v):
    Mv=mulmat(v); return [sum(u[b]*Mv[b][k] for b in range(d)) for k in range(d)]
def norm(v): return abs(int(pari.matrix(d,d,[x for r in mulmat(v) for x in r]).matdet()))
one=[-1]*d
def check_hom(q,R):
    return (sum(R)+1)%q==0 and all((R[i]*R[j]-sum(prod[i][j][k]*R[k] for k in range(d)))%q==0 for i in range(d) for j in range(d)) and len(set(tuple(R[j:]+R[:j]) for j in range(d)))==d
def hom(q):
    for t in range(0,30):
        th=[0]*d; th[0]=1; th[1]+=t
        pw=[[x%q for x in one]]
        for k in range(1,d+1): pw.append([x%q for x in mul(pw[-1],th)])
        P=pari.matrix(d,d,[x for r in pw[:d] for x in r])*pari.Mod(1,q)
        if pari.matdet(P)==0: continue
        Pinv=P**(-1); w=pari.vector(d,pw[d])*Pinv
        f=pari('x')**d-pari.Pol(list(reversed([w[k] for k in range(d)])))
        roots=pari.polrootsmod(pari.lift(f),q)
        if len(roots)!=d: return None
        rho=int(pari.lift(roots[0])); rp=[pow(rho,k,q) for k in range(d)]
        R=[sum(int(pari.lift(Pinv[i,k]))*rp[k] for k in range(d))%q for i in range(d)]
        return R if check_hom(q,R) else None
    if q**d<=3*10**6:                                 # small q: search all of F_q^d
        for R in itertools.product(range(q),repeat=d):
            if check_hom(q,list(R)): return list(R)
    return None
split=[q for q in range(2,Y) if pari.isprime(q) and q!=l and pow(q,(l-1)//d,l)==1]
R={}
for q in split:
    r=hom(q)
    if r is not None: R[q]=r
rows=[]; nel=0
for b in itertools.product(range(-B,B+1),repeat=d):
    nzb=[x for x in b if x]
    if not nzb or nzb[0]<0: continue
    x=norm(list(b)); nel+=1
    if x==0: continue
    while x%l==0: x//=l
    fac=[]
    for q in R:
        k=0
        while x%q==0: x//=q; k+=1
        if k: fac.append((q,k))
    if x!=1 or not fac: continue
    row={}; ok=True
    for q,k in fac:
        J=[j for j in range(d) if sum(b[i]*R[q][(i+j)%d] for i in range(d))%q==0]
        if len(J)!=k: ok=False; break
        e=[0]*d
        for j in J: e[j]=1
        v=[e[t]-e[d-1] for t in range(d-1)]
        if any(v): row[q]=v
    if ok and row: rows.append(row)
def run(rows,label):
    T,g1,st=own_span([dict(r) for r in rows],d,8)
    import span
    from flint import fmpz_poly
    class Fd: N=d
    buf=io.StringIO()
    with contextlib.redirect_stdout(buf): T2,g2=span.prove(Fd,[{q:fmpz_poly(v) for q,v in r.items()} for r in rows],0)
    print("%s: l=%d d=%d h=%d: %d elements, %d rows, |T| = %d (own) / %d (span.py, after its step (a)), smallest %s; gcd: own %d, span.prove %d"%(label,l,d,h,nel,len(rows),len(T),len(T2),T[:6],g1,g2),flush=True)
    return g1,g2
g1,g2=run(rows,"control")
okv=lambda g:(g==1) if h==1 else (g!=1 and (g==0 or True))
need(g1!=0 and g2!=0,"no result (rank)")
need((g1==1)==(h==1) and (g2==1)==(h==1),"CONTROL FAILED")
print("  as expected (%s)"%("gcd 1" if h==1 else "gcd > 1; gcd/h = %s, %s"%(g1/h,g2/h)))
if tamper:
    random.seed(l*d); res=[]
    for trial in range(5):
        rr=[dict(r) for r in rows]; i=random.randrange(len(rr)); q=random.choice(sorted(rr[i]))
        e=rr[i][q]; top=e[-1]; rr[i][q]=[-top]+[e[k-1]-top for k in range(1,d-1)]      # x * e
        res.append(run(rr,"  tampered (row %d, prime %d, entry times x)"%(i,q)))
    print("  after tampering with ONE entry: gcds (own, span.prove) =",res)
