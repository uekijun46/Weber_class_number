#!/usr/bin/env python3
# Rigorous verifier: prime ideals of k_p are principal, proved from many relations at once by linear algebra over Z[zeta_p].
# Only exact integer arithmetic (python-flint).  This part uses no hypothesis.  The last step (the bound of the class number)
# uses the generalized Riemann hypothesis and is printed separately.
#
# Field: K = k_p (first layer, N = p), notation as in verify.py: M = p^2, eta_i (i mod p), alpha = c + sum_i a_i eta_i.
#   tau: eta_i -> eta_(i+1) generates G = Gal(K/Q);  s = tau^(-1).
# Facts used:
#   (1) A prime q != p splits completely in K iff q^(p-1) = 1 mod p^2.  The prime ideal above p is principal.
#   (2) Let q be a split prime, f the order of q modulo M, m an irreducible polynomial of degree f over F_q (irreducibility is
#       proved by Rabin's test), and z an element of order M of the field F_q[t]/(m).  Then zeta -> z is a ring homomorphism
#       Z[zeta] -> F_q[t]/(m), and its kernel is a prime ideal above q.  The images R_i of eta_i lie in F_q (checked).
#       Put phi: O_K -> F_q, eta_i -> R_i, and Q_q = ker(phi).  The p prime ideals above q are s^j(Q_q) = ker(phi tau^j), j mod p.
#   (3) Let |N(alpha)| = p^a prod_q q^(k_q) with split primes q.  If for every q exactly k_q of the p values
#       phi(tau^j(alpha)) = c + sum_i a_i R_(i+j) vanish, say for j in J_q, then (alpha) = P^a prod_q prod_{j in J_q} s^j(Q_q),
#       where P is the prime ideal above p.  Hence  sum_q (sum_{j in J_q} s^j) [Q_q] = 0  in the class group Cl of K.
#   (4) Cl is a module over Z[G], and the element sum_j s^j acts as zero (the norm of an ideal is a principal ideal of Z).
#       So Cl is a module over A = Z[x]/(1 + x + ... + x^(p-1)), where s acts as x.  Let T be a finite set of split primes and let
#       L be the A-submodule of A^T generated by the vectors of (3) of elements whose norms contain only p and primes of T.
#       The classes [Q_q], q in T, generate a quotient of A^T/L.  If L = A^T, then every prime ideal above a prime of T is principal.
# How the program proves L = A^T:
#   (a) Before anything else: a prime that occurs in only one row is removed from T together with this row (repeated).
#   (b) Pivot: if a row r has the entry +-x^j (a unit of A) at the prime q, multiples of r are subtracted from the other rows so
#       that their entries at q become 0; then r and q are removed.  The module A^T/L does not change up to isomorphism.
#       A row may be dropped at any time (this makes L smaller).
#   (c) For the remaining n primes: if C is the matrix over A of n of the rows, then the rows of C generate a submodule of
#       index |Nm(det C)| in A^n if this number is not 0 (Nm: norm of Q(zeta_p)/Q).  If the greatest common divisor of these
#       numbers for several choices of the n rows is 1, then the rows generate A^n.
#       If the greatest common divisor is a power p^e with e > 0, then the rows generate a submodule of A^T whose index is a
#       power of p; so the classes [Q_q], q in T, generate a p-group.  The class number of K is not divisible by p (Iwasawa:
#       K/Q is cyclic of degree p and exactly one prime ramifies), so these classes are trivial also in this case.
#       Nm(det C) is computed modulo primes l = 1 mod p as prod_{k=1}^{p-1} det C(w^k), w of order p modulo l, and recovered by
#       the Chinese remainder theorem using  Nm(det C)^2 <= prod_i (t_i/(p-1))^(p-1)  (Hadamard and the inequality of the
#       means), where t_i is the sum over the entries e = sum_{j<p} e_j x^j of the row i of  Tr(e conj(e)) = p sum e_j^2 - (sum e_j)^2.
# Certificate lines:  "c | i:a i:a ... | r^e r^e ..."   with |N(c + sum a_i eta_i)| = prod r^e, every r equal to p or a split prime.
#   python3 span.py CERT [--core n] [--rows a,b] [--primes OUT]     (--core, --rows: when step (b) stops and how many rows it keeps)
import sys, math
if hasattr(sys,"set_int_max_str_digits"): sys.set_int_max_str_digits(0)      # the numbers of digits of large integers are printed
from flint import fmpz, fmpz_poly, nmod_poly, nmod_mat
from verify import K, need, is_prime, parse_coef, up, down
def rabin_irreducible(m,q,f):                         # Rabin's test for a monic polynomial m of degree f over F_q
    t=nmod_poly([0,1],q)
    def frob(k):                                      # t^(q^k) mod m
        y=t
        for _ in range(k): y=y.pow_mod(q,m)
        return y
    if (frob(f)-t)%m!=0: return False
    for r in range(2,f+1):
        if f%r==0 and is_prime(r) and (m.gcd((frob(f//r)-t)%m)).degree()!=0: return False
    return True
def periods(F,q):                                     # fact (2): R_i = phi(eta_i) in F_q
    M=F.M; need(is_prime(q) and F.split(q),"%d is not a split prime"%q)
    rs=[r for r in range(2,M+1) if M%r==0 and is_prime(r)]            # z has order M iff z^M = 1 and z^(M/r) != 1 for all r
    f=1
    while pow(q,f,M)!=1: f+=1
    m=None
    if f==1: m=nmod_poly([0,1],q)                     # F_q itself
    else:
        base=min(q,200)                               # candidates t^f + (polynomial whose coefficients are the digits of k in this base)
        for k in range(1,20000):
            co=[]; v=k
            while v: co.append(v%base); v//=base
            if len(co)>f or co[0]==0: continue
            cand=nmod_poly(co+[0]*(f-len(co))+[1],q)
            if rabin_irreducible(cand,q,f): m=cand; break
    need(m is not None,"%d: no irreducible polynomial found"%q)
    z=None
    for a in range(2,400):
        y=nmod_poly([a,1],q).pow_mod((q**f-1)//M,m) if f>1 else nmod_poly([pow(a,(q-1)//M,q)],q)
        if all((y.pow_mod(M//r,m)!=1) if f>1 else (pow(int(y[0]),M//r,q)!=1) for r in rs): z=y; break
    need(z is not None,"%d: no element of order M found"%q)
    zp=[nmod_poly([1],q)]
    for _ in range(M): zp.append(zp[-1]*z%m if f>1 else nmod_poly([int(zp[-1][0])*int(z[0])%q],q))
    need(zp[M]==1 and all(zp[M//r]!=1 for r in rs),"%d: order of z"%q)
    R=[]
    for ex in F.exps:
        s=nmod_poly([0],q)
        for e in ex: s=s+zp[e]
        need(s.degree()<=0,"%d: a period is not in F_q"%q); R.append(int(s[0]))
    return R
def read_cert(F,fn):
    p=F.p; first=True
    for line in open(fn):
        line=line.strip()
        if first:
            need(line.split()[:2]==["#","field"] and [int(v) for v in line.split()[2:4]]==[F.p,F.n],"field line"); first=False
        if not line or line.startswith("#"): continue
        cs_,coefs,facs=line.split("|"); c=int(cs_); coef=parse_coef(coefs)
        fac=[(int(t.split("^")[0]),int(t.split("^")[1])) for t in facs.split()]
        need(all(0<=i<F.N and a!=0 for i,a in coef) and len(set(i for i,a in coef))==len(coef),"coefficients: "+line)
        prod=1
        for r,e in fac:
            need(e>=1 and is_prime(r) and (r==p or F.split(r)),"factor %d is not p or a split prime: "%r+line); prod*=r**e
        need(len(set(r for r,e in fac))==len(fac) and F.norm(c,coef)==prod,"norm: "+line)
        yield c,coef,[(r,e) for r,e in fac if r!=p]
class Ring:                                           # A = Z[x]/(Phi_p); elements are fmpz_poly of degree <= p-2
    def __init__(self,p):
        self.p=p; self.Phi=fmpz_poly([1]*p); self.zero=fmpz_poly([])
    def red(self,a): return a%self.Phi
    def mono(self,j,sign=1): return self.red(fmpz_poly([0]*(j%self.p)+[sign]))
    def unit(self,a):                                 # (sign, j) if a = sign x^j in A, otherwise None
        co=[int(v) for v in a.coeffs()]; nz=[j for j,v in enumerate(co) if v]
        if len(nz)==1 and abs(co[nz[0]])==1: return co[nz[0]],nz[0]
        if len(co)==self.p-1 and (all(v==1 for v in co) or all(v==-1 for v in co)): return -co[0],self.p-1   # x^(p-1) = -(1+...+x^(p-2))
        return None
def relation_rows(F,rels):                            # fact (3): rels yields (c, coef, [(q, k), ...]) with verified norms
    N=F.N; A=Ring(N); R={}; rows=[]; nrel=0
    for c,coef,fac in rels:
        nrel+=1; row={}
        for q,k in fac:
            if q not in R: R[q]=periods(F,q)
            Rq=R[q]; J=[j for j in range(N) if (c+sum(a*Rq[(i+j)%N] for i,a in coef))%q==0]
            need(len(J)==k,"the number of prime ideals above %d that contain the element is not the exponent of %d in the norm"%(q,q))
            e=[0]*N
            for j in J: e[j]=1
            row[q]=A.red(fmpz_poly(e))
        row={q:v for q,v in row.items() if v!=A.zero}  # the entry is 0 in A if all prime ideals above q contain the element
        if row: rows.append(row)
    print("relations verified (norms and prime ideal factorizations): %d; primes: %d"%(nrel,len(R)),flush=True)
    return rows
def ppower(g,p):                                      # is the positive integer g a power of p (including 1)?
    while g%p==0: g//=p
    return g==1
def prove(F,rows,core,cap=None):                      # returns T and the gcd of (c); every prime of T is principal if the gcd is a power of the degree
    # The conclusion for a gcd p^e with e > 0 needs that p does not divide the class number.  This holds if K/Q is cyclic of
    # degree p, K is real, and exactly one prime ramifies (Iwasawa).  The callers (main: K = k_p; span_test.py: prime conductor,
    # odd prime degree) satisfy this; prove() itself does not check it.
    # core: step (b) stops when this many primes remain; cap = (a, b): rows are dropped when there are more than a * (primes) + b
    p=F.N; need(is_prime(p),"the degree must be prime"); A=Ring(p)
    # (a) primes that occur in one row only
    col={}
    for i,r in enumerate(rows):
        for q in r: col.setdefault(q,set()).add(i)
    alive=set(range(len(rows))); ch=True
    while ch:
        ch=False
        for q in sorted(q for q,s in col.items() if len(s)<=1):
            for i in col.pop(q):
                for q2 in rows[i]:
                    if q2!=q: col[q2].discard(i)
                alive.discard(i)
            ch=True
    T=sorted(col); need(T,"no primes left")
    need(all(set(rows[i])<=set(T) for i in alive),"a row contains a removed prime")
    print("(a) T: %d primes (smallest %d, largest %d); rows: %d"%(len(T),T[0],T[-1],len(alive)),flush=True)
    # (b) pivots that are units +-x^j
    def drop(i):
        for q in rows[i]: col[q].discard(i)
        alive.discard(i)
    npiv=0
    while len(col)>core:
        if cap is not None and len(alive)>cap[0]*len(col)+cap[1]:      # drop the rows with the most entries
            for i in sorted(alive,key=lambda i:(-len(rows[i]),i))[:len(alive)-(cap[0]*len(col)+cap[1])]: drop(i)
        best=None; order=sorted(col,key=lambda q:(len(col[q]),q))
        for t,q in enumerate(order):
            if t>=40 and best is not None: break
            for i in sorted(col[q]):
                u=A.unit(rows[i][q])
                if u is not None:
                    cost=((len(rows[i])-1)*(len(col[q])-1),q,i)
                    if best is None or cost<best[0]: best=(cost,u)
        if best is None: break
        (cost,q,i),(sg,j)=best; r=rows[i]; inv=A.mono(p-j,sg)
        need(A.red(r[q]*inv)==fmpz_poly([1]),"inverse of the pivot")
        for k in sorted(col[q]):
            if k==i: continue
            rk=rows[k]; fct=A.red(rk[q]*inv)
            for q2,x in r.items():
                if q2==q: continue
                y=rk.get(q2,A.zero)-A.red(fct*x)
                if y!=A.zero: rk[q2]=y; col[q2].add(k)
                elif q2 in rk: del rk[q2]; col[q2].discard(k)
            del rk[q]
            if not rk: alive.discard(k)
        drop(i); del col[q]; npiv+=1
    cols=sorted(col); n=len(cols)
    need(all(set(rows[i])<=set(cols) for i in alive),"a row contains a removed prime")
    print("(b) pivots: %d; remaining: %d primes, %d rows"%(npiv,n,len(alive)),flush=True)
    # (c) determinants
    g=0; nblocks=0
    if n>0:
        tr=lambda e:(lambda co:p*sum(v*v for v in co)-sum(co)**2)([int(v) for v in e.coeffs()])
        cand=sorted(alive,key=lambda i:(sum(tr(e) for e in rows[i].values()),i))
        l=(2**62//p)*p+1; ls=[]
        def prime(k):                                  # the k-th auxiliary prime l = 1 mod p with an element w of order p
            nonlocal l
            while len(ls)<=k:
                l-=p
                while not is_prime(l): l-=p
                w=next(pow(a,(l-1)//p,l) for a in range(2,200) if pow(a,(l-1)//p,l)!=1)
                need(pow(w,p,l)==1 and w!=1,"root of unity"); ls.append((l,w))
            return ls[k]
        for b in range(len(cand)//n):
            blk=cand[b*n:(b+1)*n]
            ent=[[[int(v) for v in rows[i].get(q,A.zero).coeffs()] for q in cols] for i in blk]
            ts=[sum(p*sum(v*v for v in e)-sum(e)**2 for e in rw) for rw in ent]
            if min(ts)==0: continue
            num=math.prod(ts)**(p-1); den=(p-1)**(n*(p-1)); bound=math.isqrt(num//den+1)+1      # |Nm(det C)| <= bound
            flat=[(e[d] if d<len(e) else 0) for rw in ent for e in rw for d in range(p-1)]
            mod=1; res=0; k=0
            while mod<=2*bound:
                lq,w=prime(k); k+=1
                E=nmod_mat(n*n,p-1,flat,lq); V=nmod_mat(p-1,p-1,[pow(w,(e+1)*d,lq) for d in range(p-1) for e in range(p-1)],lq)
                EV=(E*V).entries(); v=1
                for e in range(p-1): v=v*int(nmod_mat(n,n,EV[e::p-1],lq).det())%lq
                res=res+mod*((v-res)*pow(mod,-1,lq)%lq); mod*=lq
            if res>mod//2: res-=mod
            D=abs(res); nblocks+=1; g=math.gcd(g,D)
            print("(c) set %d of %d rows: Nm(det) %s (%d auxiliary primes); gcd so far %s"%(nblocks,n,"= 0" if D==0 else "has %d digits"%len(str(D)),k,"= %d"%g if g<10**6 else "has %d digits"%len(str(g))),flush=True)
            if g!=0 and ppower(g,p): break
    return T,(g if n>0 else 1)
def main():
    args=sys.argv[1:]; fn=args[0]; opt={args[i]:args[i+1] for i in range(1,len(args)-1) if args[i].startswith("--")}
    hd=open(fn).readline().split(); need(hd[:2]==["#","field"] and int(hd[3])==1,"the certificate must begin with '# field p 1'")
    F=K(int(hd[2]),1); p=F.p
    T,g=prove(F,relation_rows(F,read_cert(F,fn)),int(opt.get("--core",120)),tuple(int(v) for v in opt.get("--rows","4,400").split(",")))
    need(g!=0 and ppower(g,p),"(c): the greatest common divisor of the indices is not a power of p")
    if g!=1: print("(c) the greatest common divisor is %d, a power of p; the conclusion uses that p does not divide the class number (Iwasawa)"%g)
    print("SPAN PASS  field k_%d: the prime ideals above the %d split primes of T are principal (%s)."%(p,len(T),"no hypothesis" if g==1 else "GRH is not used; Iwasawa's theorem is used"))
    print("  T: smallest %s, largest %d; %d of them below 10^6"%(T[:6],T[-1],sum(1 for q in T if q<10**6)))
    if "--primes" in opt: open(opt["--primes"],"w").write("# field %d 1: split primes whose prime ideals are principal (span.py %s)\n"%(p,fn)+"".join("%d\n"%q for q in T))
    # the class number, UNDER GRH
    from bound_grh import bound_grh
    from flint import arb
    hm=F.hmin(); best=None
    for c2 in range(8,29):
        c=arb(c2)/2; G_up,S_low,B,hb=bound_grh(F,T,c)
        if hb is not None and (best is None or hb<best[0]): best=(hb,c2/2,G_up,S_low,B)
    need(best is not None,"UNDER GRH: B <= 0 for every c")
    hb,c,G_up,S_low,B=best
    print("UNDER GRH (Miller, Lemma 5.2): c=%s: G(c) <= %s, prime sum >= %s, B >= %s, h < %s; least possible class number > 1: %d"%(c,up(G_up,10),down(S_low,10),down(B,7),up(hb,4),hm))
    print("VERDICT (under GRH): PASS  (h < %s < %d)"%(up(hb,4),hm) if hb<hm else "VERDICT (under GRH): bound not below %d"%hm)
if __name__=="__main__": main()
